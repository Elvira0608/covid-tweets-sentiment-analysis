def custom_tokenizer(text):
  tokens = tw.tokenize(text.lower())
  tokens = [token for token in tokens if token not in noise]
  tokens = [token for token in tokens if not (len(token) == 1 and ord(token[0]) >= 128)]
  tokens = [token for token in tokens if 'https://t.co' not in token]
  return tokens

